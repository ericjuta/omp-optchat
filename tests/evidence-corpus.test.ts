import { describe, expect, test } from "bun:test";
import {
	ADVERSARIAL_KINDS,
	buildCorpus,
	CODENAMES,
	type Corpus,
	describeCorpusSize,
	estimateCorpusSize,
	factRecordCount,
	MAX_OVERSHOOT_BYTES,
	MAX_PROJECTS,
	MAX_SOURCE_BYTES,
	MAX_SOURCES,
	MIN_PROJECTS,
	MIN_SOURCE_BYTES,
	MIN_SOURCES,
	questionCount,
	QUESTION_KINDS,
	type Question,
	UNSTATED_SUBJECT,
} from "../scripts/evidence/corpus.ts";

/** Exactly one record whose text contains the fragment; its record id. */
function recordWith(corpus: Corpus, fragment: string): number {
	const hits = corpus.sources.filter((source) => source.text.includes(fragment));
	if (hits.length !== 1) throw new Error(`expected one record containing "${fragment}", found ${hits.length}`);
	return hits[0]!.recordId;
}

/** A corpus with the minimal fact plan plus filler, so late corrections sit well after the facts. */
function shaped(projects: number, seed: number, minSourceBytes = MIN_SOURCE_BYTES, filler = 3): Corpus {
	return buildCorpus({ seed, projects, sourceCount: factRecordCount(projects) + filler, minSourceBytes });
}

const SEEDS = Array.from({ length: 25 }, (_, index) => index);
const PROJECT_SHAPES = [2, 4, 7] as const;

describe("corpus capacity and sizing", () => {
	test("the record plan matches the closed form and the generated records at every project count", () => {
		for (let projects = MIN_PROJECTS; projects <= MAX_PROJECTS; projects++) {
			const closed = 6 * projects + 5 * Math.floor(projects / 4) + [0, 0, 1, 3][projects % 4]! + 3;
			expect(factRecordCount(projects)).toBe(closed);
			const minimal = buildCorpus({ seed: 1, projects, sourceCount: factRecordCount(projects), minSourceBytes: MIN_SOURCE_BYTES });
			expect(minimal.sources.length).toBe(factRecordCount(projects));
			expect(minimal.questions.length).toBe(questionCount(projects));
		}
	});

	test("one fewer source than the fact plan needs is refused; the exact plan is accepted", () => {
		for (const projects of [MIN_PROJECTS, 3, 4, MAX_PROJECTS]) {
			const needed = factRecordCount(projects);
			expect(() => buildCorpus({ seed: 1, projects, sourceCount: needed - 1, minSourceBytes: MIN_SOURCE_BYTES })).toThrow();
			expect(buildCorpus({ seed: 1, projects, sourceCount: needed, minSourceBytes: MIN_SOURCE_BYTES }).sources.length).toBe(needed);
		}
	});

	test("the project, source, and byte ceilings and floors are enforced at their edges", () => {
		const ok = { seed: 1, minSourceBytes: MIN_SOURCE_BYTES };
		expect(() => buildCorpus({ ...ok, projects: MIN_PROJECTS - 1, sourceCount: MAX_SOURCES })).toThrow();
		expect(() => buildCorpus({ ...ok, projects: MAX_PROJECTS + 1, sourceCount: MAX_SOURCES })).toThrow();
		expect(() => buildCorpus({ ...ok, projects: 3, sourceCount: MIN_SOURCES - 1 })).toThrow();
		expect(() => buildCorpus({ ...ok, projects: 3, sourceCount: MAX_SOURCES + 1 })).toThrow();
		expect(() => buildCorpus({ ...ok, projects: 3, sourceCount: 24, minSourceBytes: MIN_SOURCE_BYTES - 1 })).toThrow();
		expect(() => buildCorpus({ ...ok, projects: 3, sourceCount: 24, minSourceBytes: MAX_SOURCE_BYTES + 1 })).toThrow();
		expect(buildCorpus({ ...ok, projects: MAX_PROJECTS, sourceCount: MAX_SOURCES }).sources.length).toBe(MAX_SOURCES);
		expect(buildCorpus({ ...ok, projects: MIN_PROJECTS, sourceCount: MIN_SOURCES, minSourceBytes: MAX_SOURCE_BYTES }).sources.length).toBe(MIN_SOURCES);
	});

	test("every record meets the byte floor and stays within the overshoot bound, from small to largest settings", () => {
		const encoder = new TextEncoder();
		for (const minSourceBytes of [MIN_SOURCE_BYTES, 1024, 4097, MAX_SOURCE_BYTES]) {
			const corpus = shaped(3, 9, minSourceBytes, 6);
			for (const source of corpus.sources) {
				const bytes = encoder.encode(source.text).byteLength;
				expect(bytes).toBeGreaterThanOrEqual(minSourceBytes);
				expect(bytes).toBeLessThanOrEqual(minSourceBytes + MAX_OVERSHOOT_BYTES - 1);
			}
		}
	});

	test("the largest corpus honors the byte floor on every record", () => {
		const encoder = new TextEncoder();
		const corpus = buildCorpus({ seed: 9, projects: MAX_PROJECTS, sourceCount: MAX_SOURCES, minSourceBytes: MAX_SOURCE_BYTES });
		expect(corpus.sources.length).toBe(MAX_SOURCES);
		for (const source of corpus.sources) {
			const bytes = encoder.encode(source.text).byteLength;
			expect(bytes).toBeGreaterThanOrEqual(MAX_SOURCE_BYTES);
			expect(bytes).toBeLessThanOrEqual(MAX_SOURCE_BYTES + MAX_OVERSHOOT_BYTES - 1);
		}
	});

	test("the sizing helper brackets the generated byte total and matches the generated question count", () => {
		const encoder = new TextEncoder();
		for (const projects of PROJECT_SHAPES) {
			const options = { seed: 5, projects, sourceCount: factRecordCount(projects) + 4, minSourceBytes: 2048 };
			const corpus = buildCorpus(options);
			const size = describeCorpusSize(options);
			const total = corpus.sources.reduce((sum, source) => sum + encoder.encode(source.text).byteLength, 0);
			expect(size.sources).toBe(corpus.sources.length);
			expect(size.questions).toBe(corpus.questions.length);
			expect(total).toBeGreaterThanOrEqual(size.minBytes);
			expect(total).toBeLessThanOrEqual(size.maxBytes);
			expect(size.approxTokens.min).toBeLessThanOrEqual(size.approxTokens.max);
		}
	});

	test("the minimal-size estimate matches the smallest buildable corpus", () => {
		for (const projects of [MIN_PROJECTS, 3, 10, MAX_PROJECTS]) {
			const estimate = estimateCorpusSize(projects);
			const smallest = buildCorpus({ seed: 2, projects, sourceCount: estimate.minSources, minSourceBytes: MIN_SOURCE_BYTES });
			expect(estimate.minSources).toBe(Math.max(MIN_SOURCES, factRecordCount(projects)));
			expect(estimate.questions).toBe(smallest.questions.length);
		}
	});

	test("the default shape keeps the runner defaults valid: two projects sixteen records, three projects twenty-four", () => {
		expect(factRecordCount(2)).toBe(16);
		expect(factRecordCount(3)).toBe(24);
	});
});

describe("corpus contents", () => {
	test("same seed and shape reproduce the digest; another seed or byte floor changes it", () => {
		for (const projects of PROJECT_SHAPES) {
			const base = shaped(projects, 11, 1024);
			expect(shaped(projects, 11, 1024).digest).toBe(base.digest);
			expect(shaped(projects, 12, 1024).digest).not.toBe(base.digest);
			expect(shaped(projects, 11, 2048).digest).not.toBe(base.digest);
		}
	});

	test("names are unique, cover the largest project count, and never collide with the unstated or Atlas entities", () => {
		expect(CODENAMES.length).toBe(MAX_PROJECTS);
		expect(new Set(CODENAMES).size).toBe(CODENAMES.length);
		for (const name of CODENAMES) {
			expect(name).not.toBe(UNSTATED_SUBJECT);
			expect(name.startsWith("Atlas")).toBe(false);
		}
	});

	test("ticket IDs are unique within a corpus across seeds at the largest project count", () => {
		for (const seed of [0, 1, 2, 3, 4, 5]) {
			const corpus = buildCorpus({ seed, projects: MAX_PROJECTS, sourceCount: factRecordCount(MAX_PROJECTS), minSourceBytes: MIN_SOURCE_BYTES });
			expect(corpus.knownIds.length).toBe(MAX_PROJECTS);
			expect(new Set(corpus.knownIds).size).toBe(MAX_PROJECTS);
			expect(corpus.knownIds).toEqual([...corpus.knownIds].sort());
		}
	});

	test("every record embeds its REF exactly once, numbers records in order, and tags work records", () => {
		for (const seed of SEEDS.slice(0, 5)) {
			const corpus = shaped(4, seed, 512, 9);
			corpus.sources.forEach((source, index) => {
				expect(source.recordId).toBe(index);
				expect(source.ref).toBe(`REF-${seed}-${index}`);
				expect(source.text.split(`[${source.ref}]`).length).toBe(2);
			});
		}
	});

	test("facts sit early, a project's facts are spread a whole fact layer apart, and late corrections follow all filler", () => {
		const projects = 7;
		const filler = 11;
		const corpus = shaped(projects, 3, 512, filler);
		const owner = recordWith(corpus, `Project ${CODENAMES[0]} owner is`);
		expect(owner).toBeLessThan(projects);
		const vendor = recordWith(corpus, `Project ${CODENAMES[0]} uses vendor`);
		expect(vendor - owner).toBe(projects);
		const fillerIds = corpus.sources.filter((source) => source.text.startsWith("Filler")).map((source) => source.recordId);
		expect(fillerIds.length).toBe(filler);
		const correctionIds = corpus.sources.filter((source) => source.text.startsWith("Correction") || source.text.startsWith("Revert")).map((source) => source.recordId);
		expect(correctionIds.length).toBeGreaterThan(0);
		for (const id of correctionIds) expect(id).toBeGreaterThan(Math.max(...fillerIds));
	});
});

describe("corpus questions", () => {
	test("the four global questions and six per-project questions are present for every shape", () => {
		for (const projects of PROJECT_SHAPES) {
			const corpus = shaped(projects, 4);
			expect(corpus.questions.length).toBe(questionCount(projects));
			for (const id of ["atlas-north-definite", "atlas-ambiguous", "obsidian-unstated", "work-checksum"]) {
				expect(corpus.questions.some((question) => question.id === id)).toBe(true);
			}
		}
	});

	test("every kind appears once the corpus has all four project families", () => {
		const corpus = shaped(4, 6);
		const kinds = new Set(corpus.questions.map((question) => question.kind));
		for (const kind of QUESTION_KINDS) expect(kinds.has(kind)).toBe(true);
		expect(QUESTION_KINDS.length).toBe(13);
		expect(ADVERSARIAL_KINDS.every((kind) => QUESTION_KINDS.includes(kind))).toBe(true);
	});

	test("answerable questions expect values their sources state; forbidden values are never expected; forbidden values appear in the corpus", () => {
		for (const seed of SEEDS) {
			for (const projects of PROJECT_SHAPES) {
				const corpus = shaped(projects, seed, 512, 4);
				const texts = corpus.sources.map((source) => source.text).join("\n");
				for (const question of corpus.questions.filter((entry) => entry.answerable && !entry.ambiguous)) {
					expect(question.expect.length).toBeGreaterThan(0);
					for (const value of question.expect) {
						expect(question.forbid).not.toContain(value);
						expect(question.sources.some((source) => corpus.sources[source.recordId]!.text.includes(value))).toBe(true);
					}
					for (const source of question.sources) expect(corpus.sources[source.recordId]!.text).toContain(source.value);
					for (const value of question.forbid) expect(texts).toContain(value);
				}
			}
		}
	});

	test("ambiguous questions name exactly their candidates, cite every candidate's source, and assert nothing definite", () => {
		for (const seed of SEEDS.slice(0, 5)) {
			const corpus = shaped(3, seed);
			const ambiguous = corpus.questions.find((question) => question.kind === "ambiguity")!;
			expect(ambiguous.ambiguous).toBe(true);
			expect(ambiguous.expect).toEqual([]);
			expect(ambiguous.forbid).toEqual([]);
			expect(ambiguous.candidates.length).toBe(2);
			expect(new Set(ambiguous.candidates).size).toBe(2);
			expect(ambiguous.sources.map((source) => source.value).sort()).toEqual([...ambiguous.candidates].sort());
			for (const source of ambiguous.sources) expect(corpus.sources[source.recordId]!.text).toContain(source.value);
		}
	});

	test("the near-duplicate pair is definite on one name and ambiguous on the bare name", () => {
		const corpus = shaped(3, 8);
		const definite = corpus.questions.find((question) => question.id === "atlas-north-definite")!;
		const bare = corpus.questions.find((question) => question.id === "atlas-ambiguous")!;
		expect(definite.prompt).toBe("Who owns Atlas-North?");
		expect(definite.ambiguous).toBe(false);
		expect(definite.expect.length).toBe(1);
		expect(definite.forbid.length).toBe(1);
		expect(definite.expect[0]).not.toBe(definite.forbid[0]);
		expect(recordWith(corpus, `Atlas-North owner is ${definite.expect[0]}.`)).toBe(definite.sources[0]!.recordId);
		expect(recordWith(corpus, `Atlas North-2 owner is ${definite.forbid[0]}.`)).toBeGreaterThan(-1);
		expect(bare.prompt).toBe("Who owns Atlas North?");
		expect(bare.candidates).toEqual([definite.expect[0], definite.forbid[0]]);
	});

	test("the unanswerable question names a subject the corpus never states", () => {
		for (const seed of SEEDS.slice(0, 5)) {
			const corpus = shaped(4, seed);
			const unanswerable = corpus.questions.find((question) => question.kind === "unanswerable")!;
			expect(unanswerable.answerable).toBe(false);
			expect(unanswerable.ambiguous).toBe(false);
			expect(unanswerable.expect).toEqual([]);
			expect(unanswerable.forbid).toEqual([]);
			expect(unanswerable.candidates).toEqual([]);
			expect(unanswerable.sources).toEqual([]);
			expect(unanswerable.prompt).toContain(UNSTATED_SUBJECT);
			for (const source of corpus.sources) expect(source.text).not.toContain(UNSTATED_SUBJECT);
		}
	});

	test("every answerable question has its sources and a single-value answer", () => {
		const corpus = shaped(4, 2);
		for (const question of corpus.questions.filter((entry) => entry.answerable)) {
			if (question.kind === "ambiguity") continue;
			expect(question.sources.length).toBeGreaterThan(0);
			expect(question.sources.every((source) => source.recordId >= 0 && source.recordId < corpus.sources.length)).toBe(true);
		}
		expect(corpus.questions.filter((question) => !question.answerable).length).toBe(1);
	});
});

describe("adversarial structure", () => {
	/** The owner question for one project; its kind depends on the project family. */
	function ownerOf(corpus: Corpus, projectIndex: number): Question {
		const name = CODENAMES[projectIndex]!;
		return corpus.questions.find((question) => question.id === `owner-${name}`)!;
	}

	test("a multi-step correction supersedes both earlier owners in order", () => {
		const corpus = shaped(3, 13, 512, 5);
		const chain = ownerOf(corpus, 2);
		expect(chain.kind).toBe("multi-step-correction");
		const [original, interim] = chain.forbid;
		const originalId = recordWith(corpus, `Project ${CODENAMES[2]} owner is ${original}.`);
		const interimId = recordWith(corpus, `Correction for project ${CODENAMES[2]}: owner is ${interim}, not ${original}.`);
		const finalId = recordWith(corpus, `Correction for project ${CODENAMES[2]}: owner is ${chain.expect[0]}, not ${interim}.`);
		expect(originalId).toBeLessThan(interimId);
		expect(interimId).toBeLessThan(finalId);
		expect(chain.sources[0]!.recordId).toBe(finalId);
		expect(chain.expect.length).toBe(1);
		expect(chain.forbid.length).toBe(2);
	});

	test("a reverted correction stands on the original owner and rejects the retracted one", () => {
		const corpus = shaped(4, 13, 512, 5);
		const revert = ownerOf(corpus, 3);
		expect(revert.kind).toBe("reverted-correction");
		const [retracted] = revert.forbid;
		const original = revert.expect[0]!;
		const originalId = recordWith(corpus, `Project ${CODENAMES[3]} owner is ${original}.`);
		const retractionId = recordWith(corpus, `Correction for project ${CODENAMES[3]}: owner is ${retracted}, not ${original}.`);
		const revertId = recordWith(corpus, `Revert for project ${CODENAMES[3]}: ${retracted} was wrong, ${original} stands.`);
		expect(originalId).toBeLessThan(retractionId);
		expect(retractionId).toBeLessThan(revertId);
		expect(revert.sources.map((source) => source.recordId)).toEqual([originalId, revertId]);
		for (const source of revert.sources) expect(corpus.sources[source.recordId]!.text).toContain(original);
	});

	test("a late distractor repeats the rejected vendor after the vendor fact it contradicts", () => {
		const corpus = shaped(3, 21, 512, 5);
		const name = CODENAMES[1]!;
		const distractor = corpus.questions.find((question) => question.id === `distractor-${name}`)!;
		expect(distractor.kind).toBe("late-distractor");
		const [rejected] = distractor.forbid;
		const vendorFactId = recordWith(corpus, `Project ${name} uses vendor ${distractor.expect[0]}; it does not use vendor ${rejected}.`);
		const distractorId = recordWith(corpus, `Late review for project ${name}: vendor ${rejected} was pitched, reviewed again, and rejected.`);
		expect(distractorId).toBeGreaterThan(vendorFactId);
		expect(distractor.sources[0]!.recordId).toBe(vendorFactId);
	});

	test("every correction-family question's record comes after the owner fact it supersedes, far apart", () => {
		for (const seed of SEEDS.slice(0, 8)) {
			const projects = 6;
			const filler = 8;
			const corpus = shaped(projects, seed, 512, filler);
			for (let index = 0; index < projects; index++) {
				const question = ownerOf(corpus, index);
				if (question.kind === "merge-depth") continue;
				const ownerId = recordWith(corpus, `Project ${CODENAMES[index]} owner is ${question.kind === "reverted-correction" ? question.expect[0] : question.forbid[0]}.`);
				const lateId = question.sources[question.sources.length - 1]!.recordId;
				expect(lateId - ownerId).toBeGreaterThan(filler);
			}
		}
	});

	test("the corpus has the advertised adversarial kinds at four projects and the plain merge-depth kind is still present", () => {
		const corpus = shaped(4, 30);
		const kinds = new Set(corpus.questions.map((question) => question.kind));
		for (const kind of ADVERSARIAL_KINDS) expect(kinds.has(kind)).toBe(true);
		expect(kinds.has("merge-depth")).toBe(true);
	});
});
